class Block1OperationEntry {
  const Block1OperationEntry({
    required this.order,
    required this.operationId,
    required this.title,
    required this.phase,
    required this.type,
    required this.result,
    required this.timestamp,
    required this.record,
    required this.hasRegistryEntry,
    required this.hasIndexEntry,
    required this.hasReport,
    required this.affectedModulesKnown,
    required this.affectedFilesKnown,
  });

  final String order;
  final String operationId;
  final String title;
  final String phase;
  final String type;
  final String result;
  final String timestamp;
  final String record;
  final bool hasRegistryEntry;
  final bool hasIndexEntry;
  final bool hasReport;
  final bool affectedModulesKnown;
  final bool affectedFilesKnown;

  bool matches(String query) {
    final normalized = query.trim().toLowerCase();
    if (normalized.isEmpty) return true;
    return [
      order,
      operationId,
      title,
      phase,
      type,
      result,
      timestamp,
      record,
    ].any((value) => value.toLowerCase().contains(normalized));
  }

  String get year {
    if (timestamp.length >= 4 &&
        int.tryParse(timestamp.substring(0, 4)) != null) {
      return timestamp.substring(0, 4);
    }
    return 'UNKNOWN';
  }

  String get month {
    if (timestamp.length >= 7 &&
        int.tryParse(timestamp.substring(5, 7)) != null) {
      return timestamp.substring(5, 7);
    }
    return 'UNKNOWN';
  }

  String get quarter {
    final value = int.tryParse(month);
    if (value == null) return 'UNKNOWN';
    return 'Q${((value - 1) ~/ 3) + 1}';
  }

  bool get isHealthy =>
      hasRegistryEntry &&
      hasIndexEntry &&
      hasReport &&
      affectedModulesKnown &&
      affectedFilesKnown;
}

